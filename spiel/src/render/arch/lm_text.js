// Breite eines Textes in Welteinheiten bei Zeichenhöhe h
export function textWidth(text, h) {
  const u = h / 6;
  let n = 0;
  for (const ch of text.toUpperCase()) n += ch === ' ' ? 3 : ch === 'I' || ch === '1' || ch === '.' ? 4.5 : 5.6;
  return Math.max(0, n - 1.6) * u;
}

// Schreibt Text mittig an (x, y0, z) auf eine Wand mit Blickrichtung ry. h = Zeichenhöhe, d = Tiefe der Buchstaben.
export function text(kit, mat, str, x, y0, z, ry, h, o = {}) {
  if (kit.detail === 0 && !o.lod) return;
  const u = h / 6, sw = (o.weight ?? 0.85) * u, d = o.depth ?? 0.12 * M;
  const total = textWidth(str, h);
  const c = Math.cos(ry), s = Math.sin(ry);
  let cur = -total / 2;
  for (const ch of str.toUpperCase()) {
    if (ch === ' ') { cur += 3 * u; continue; }
    const glyph = G[ch];
    const narrow = ch === 'I' || ch === '1' || ch === '.';
    const shift = narrow ? -1 * u : 0;
    if (glyph) for (const [x0, y0g, x1, y1g] of glyph) {
      const len = Math.hypot(x1 - x0, y1g - y0g) * u;
      const a = Math.atan2(y1g - y0g, x1 - x0);
      const mu = cur + shift + ((x0 + x1) / 2) * u, mv = ((y0g + y1g) / 2) * u;
      const geo = new THREE.BoxGeometry(len + sw, sw, d);
      kit.add(mat, geo, { x: x + c * mu, y: y0 + mv + sw / 2, z: z - s * mu, ry, rz: a });
    }
    cur += (narrow ? 4.5 : 5.6) * u;
  }
}
